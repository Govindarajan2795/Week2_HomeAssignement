let num = [10, 20, 30, 40, 50]; // Declare an array and initialize it with numeric values.
let sum = 0; //Declare a variable to store the sum
for (let i = 0; i < num.length; i++) { // Use a loop to iterate through the array
sum = sum + num[i]; //Add each element to the sum variable
}
console.log(`The sum of all number is ${sum}`); // Print the final sum
